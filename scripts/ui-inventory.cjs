#!/usr/bin/env node
'use strict';
// Read-only inventory of the UI: what exists today, with numbers computed by this script.
// Writes docs/ui-system/inventory.md. Nothing is changed in src/.   Run: npm run ui:inventory
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'ui-system', 'inventory.md');
const SKIP = new Set(['node_modules', '.next', '.git', 'coverage', 'dist', 'build', 'out']);
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');
const exists = (p) => fs.existsSync(path.join(ROOT, p));

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP.has(e.name)) walk(full, out); }
    else out.push(full);
  }
  return out;
}

const pkg = exists('package.json') ? JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')) : {};
const deps = { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) };
const srcRoot = ['src', 'app', 'components'].find((d) => exists(d)) || '.';
const files = ['src', 'app', 'components', 'pages'].flatMap((d) => walk(path.join(ROOT, d)))
  .filter((f) => !/\.(test|spec)\./.test(f) && !/__tests__/.test(f));
const code = files.filter((f) => /\.(jsx?|tsx?)$/.test(f));
const css = files.filter((f) => /\.css$/.test(f));
const read = (f) => fs.readFileSync(f, 'utf8');
const noComments = (t) => t.split(/\r?\n/).filter((l) => !/^\s*(\/\/|\/\*|\*)/.test(l)).join('\n');
const codeText = code.map((f) => ({ f: rel(f), t: noComments(read(f)) }));
const cssText = css.map((f) => ({ f: rel(f), t: read(f) }));

const tally = (re, sources) => {
  const m = new Map();
  for (const { t } of sources) for (const x of t.matchAll(re)) m.set(x[0], (m.get(x[0]) || 0) + 1);
  return m;
};
const top = (m, n = 15) => [...m.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, n);
const table = (rows, h = ['value', 'count']) => rows.length ? [`| ${h.join(' | ')} |`, `|${h.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map((c) => '`' + c + '`').join(' | ')} |`)].join('\n') : '_none found_';
const total = (m) => [...m.values()].reduce((a, b) => a + b, 0);
const list = (a) => (a.length ? a.map((x) => '- `' + x + '`').join('\n') : '_none found_');

const tailwind = !!deps.tailwindcss || exists('tailwind.config.js') || exists('tailwind.config.ts') || exists('tailwind.config.mjs') || cssText.some((c) => /@tailwind|@import\s+["']tailwindcss/.test(c.t));
const out = [];
const H = (t) => out.push('', '## ' + t, '');

out.push('# UI inventory', '', `Generated by scripts/ui-inventory.cjs on ${new Date().toISOString().slice(0, 10)}. Re-run: \`npm run ui:inventory\`. Every number below is computed from the code; nothing is hand-written.`);

H('Stack');
out.push(`- next: ${deps.next || 'not found'} | react: ${deps.react || 'not found'} | tailwindcss: ${tailwind ? (deps.tailwindcss || 'detected in css/config') : 'not detected'}`);
out.push(`- radix packages: ${Object.keys(deps).filter((d) => d.startsWith('@radix-ui/')).length} | components.json (shadcn): ${exists('components.json') ? 'yes' : 'no'} | class-variance-authority: ${deps['class-variance-authority'] ? 'yes' : 'no'}`);
out.push(`- router: ${exists('src/app') || exists('app') ? 'app router' : ''}${exists('src/pages') || exists('pages') ? ' pages router' : ''}`.replace(/: $/, ': not found'));
out.push(`- test tool: ${['vitest', 'jest', '@playwright/test', '@testing-library/react'].filter((d) => deps[d]).join(', ') || 'not found'} | scripts: ${Object.keys(pkg.scripts || {}).join(', ')}`);
out.push(`- code files scanned: ${code.length} | css files: ${css.length} | source root: ${srcRoot}`);

H('Global CSS and tokens');
const cssWithVars = cssText.filter((c) => /--[\w-]+\s*:/.test(c.t));
out.push('Files that define CSS variables or tailwind layers:', list(cssText.filter((c) => /:root|@theme|@tailwind|@import\s+["']tailwindcss/.test(c.t)).map((c) => c.f)));
const vars = [...new Set(cssWithVars.flatMap((c) => [...c.t.matchAll(/(--[\w-]+)\s*:/g)].map((m) => m[1])))];
out.push('', `CSS variables defined: ${vars.length}`, '', vars.slice(0, 80).map((v) => '`' + v + '`').join(' ') || '_none found_');
out.push('', `Dark mode: ${cssText.some((c) => /\.dark\b|\[data-theme|prefers-color-scheme:\s*dark/.test(c.t)) ? 'selector or media query found in css' : 'no dark selector found in css'}${/darkMode/.test(['tailwind.config.js', 'tailwind.config.ts'].filter(exists).map((f) => read(path.join(ROOT, f))).join('')) ? ' | tailwind darkMode configured' : ''}`);

H('Colors (literals in source)');
const colorRe = /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b|\b(?:rgba?|hsla?)\([^)]*\)/g;
const colors = tally(colorRe, [...codeText, ...cssText.filter((c) => !cssWithVars.includes(c))]);
out.push(`Outside files that define CSS variables: ${colors.size} distinct, ${total(colors)} occurrences. Top 15:`, '', table(top(colors)));

H('Spacing, radius, font size, shadow');
if (tailwind) {
  out.push('Tailwind classes in code. Spacing top 15:', '', table(top(tally(/(?<![\w-])(?:p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|gap|gap-x|gap-y|space-x|space-y)-(?:\d+(?:\.\d+)?|px|auto|\[[^\]\s]+\])(?![\w-])/g, codeText))));
  out.push('', 'Radius top 15:', '', table(top(tally(/(?<![\w-])rounded(?:-(?:t|b|l|r|tl|tr|bl|br))?(?:-(?:none|sm|md|lg|xl|2xl|3xl|full|\[[^\]\s]+\]))?(?![\w-])/g, codeText))));
  out.push('', 'Font size top 15:', '', table(top(tally(/(?<![\w-])text-(?:xs|sm|base|lg|xl|[2-9]xl|\[[^\]\s]+\])(?![\w-])/g, codeText))));
  out.push('', 'Shadow top 10:', '', table(top(tally(/(?<![\w-])shadow(?:-(?:sm|md|lg|xl|2xl|inner|none|\[[^\]\s]+\]))?(?![\w-])/g, codeText), 10)));
} else out.push('Tailwind not detected: see the css values below.');
const cssVals = (prop) => table(top(tally(new RegExp(prop + '\\s*:\\s*[^;{}]+', 'g'), cssText)));
out.push('', 'CSS padding top 15:', '', cssVals('padding'), '', 'CSS border-radius top 15:', '', cssVals('border-radius'), '', 'CSS font-size top 15:', '', cssVals('font-size'));

H('Arbitrary Tailwind values');
const arb = tally(/(?<![\w-])(?!(?:data|aria|supports|has|group|peer|min|max|nth)-)[a-z][a-z0-9-]*-\[[^\]\s]+\]/g, codeText);
out.push(`Total ${total(arb)}, distinct ${arb.size}. Top 10:`, '', table(top(arb, 10)));

H('Buttons, inputs, overlays, feedback');
const count = (re) => codeText.reduce((n, c) => n + (c.t.match(re) || []).length, 0);
const names = (re) => files.map((f) => path.basename(f)).filter((n) => re.test(n) && /\.(jsx?|tsx?)$/.test(n));
out.push(`- raw \`<button\`: ${count(/<button\b/g)} occurrences in ${codeText.filter((c) => /<button\b/.test(c.t)).length} files`);
out.push(`- raw \`<input\`/\`<textarea\`/\`<select\`: ${count(/<(input|textarea|select)\b/g)}`);
out.push('', 'Components named like a button:', list(names(/button/i)), '', 'Modal / dialog / popup / drawer / sheet:', list(names(/(modal|dialog|popup|drawer|sheet)/i)), '', 'Toast / alert / snackbar:', list(names(/(toast|alert|snackbar|notification)/i)), '', 'Spinner / loader / skeleton:', list(names(/(spinner|loader|loading|skeleton)/i)));

H('fetch( inside components/');
const fe = codeText.filter((c) => /(^|\/)components\//.test(c.f)).map((c) => [c.f, (c.t.match(/\bfetch\s*\(/g) || []).length]).filter((x) => x[1] > 0).sort((a, b) => b[1] - a[1]);
out.push(`Total ${fe.reduce((n, x) => n + x[1], 0)} in ${fe.length} files. Top 10:`, '', table(fe.slice(0, 10), ['file', 'count']));

H('Components structure');
const compRoot = ['src/components', 'components'].find(exists);
if (compRoot) {
  const dirs = fs.readdirSync(path.join(ROOT, compRoot), { withFileTypes: true }).filter((e) => e.isDirectory());
  out.push(table(dirs.map((d) => [compRoot + '/' + d.name, String(walk(path.join(ROOT, compRoot, d.name)).filter((f) => /\.(jsx?|tsx?)$/.test(f)).length)]), ['folder', 'component files']));
} else out.push('_components folder not found_');

H('Gallery page');
out.push(exists('src/app') || exists('app') ? 'App router detected: a dev-only page (for example `src/app/dev/ui/page.js`, returning notFound() in production) is possible. Not built.' : 'App router not detected: decide with the human.');
out.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out.join('\n'));
console.log('wrote ' + rel(OUT));
